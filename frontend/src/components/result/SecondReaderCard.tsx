import { BrainCircuit, Flag, HelpCircle, ListChecks } from "lucide-react";
import { Badge, Card } from "@/components/ui";
import { ms } from "@/lib/format";
import type { SecondReader } from "@/lib/types";

const CONS: Record<string, { label: string; tone: "ok" | "warn" | "bad" | "neutral" }> = {
  consistent: { label: "Consistent with the classifier", tone: "ok" },
  partially_consistent: { label: "Partially consistent", tone: "warn" },
  inconsistent: { label: "Disagrees with the classifier", tone: "bad" },
  cannot_assess: { label: "Could not assess", tone: "neutral" },
};

export default function SecondReaderCard({ sr }: { sr: SecondReader }) {
  if (!sr.available) {
    return (
      <Card title="Second reader" icon={<BrainCircuit size={18} className="text-turquoise-deep" />}>
        <p className="text-sm text-ink-soft">{sr.backend === "skipped" ? "The vision-language second reader was switched off for this run." : `Second reader unavailable${sr.error ? `: ${sr.error}` : "."}`}</p>
      </Card>
    );
  }
  const c = CONS[sr.consistency ?? "cannot_assess"] ?? CONS.cannot_assess;
  const review = sr.instance_review ?? [];
  return (
    <Card title="Second reader (vision-language model)" icon={<BrainCircuit size={18} className="text-turquoise-deep" />}
      aside={<div className="flex gap-1.5"><Badge tone={c.tone}>{c.label}</Badge>{sr.image_quality && <Badge>{`image quality: ${sr.image_quality}`}</Badge>}</div>}>
      <p className="text-[11px] text-ink-soft mb-3">
        Generated by {sr.model_id}{sr.quantized_4bit ? " (4-bit)" : ""} in {ms(sr.latency_ms)}.
        {sr.reviewed_instances ? " It was shown the photo with the numbered segmentation outlines and reviewed each one." : ""}
        {" "}It describes and cross-checks; it never overrides the measured classifier.
      </p>
      {sr.patient_summary && (
        <blockquote className="rounded-xl bg-turquoise-tint/60 border-l-4 border-turquoise-deep px-4 py-3 text-sm text-ink leading-relaxed">{sr.patient_summary}</blockquote>
      )}
      <div className="grid md:grid-cols-2 gap-4 mt-4 text-sm">
        <div>
          <h3 className="font-bold text-ink text-sm mb-1">What is visible</h3>
          <p className="text-ink-soft text-sm">{sr.visual_description ?? sr.raw ?? "–"}</p>
          {sr.observed_features && sr.observed_features.length > 0 && (
            <div className="flex flex-wrap gap-1.5 mt-2">{sr.observed_features.map((f, i) => <Badge key={i}>{f}</Badge>)}</div>
          )}
          {sr.image_quality_note && <p className="text-[11px] text-ink-soft mt-2">{sr.image_quality_note}</p>}
          {review.length > 0 && (
            <div className="mt-3">
              <h3 className="flex items-center gap-1.5 font-bold text-ink text-sm mb-1"><ListChecks size={14} /> Region-by-region review</h3>
              <ul className="space-y-1 text-xs">
                {review.map((r) => (
                  <li key={r.id} className="flex items-start gap-2">
                    <span className={`mt-0.5 inline-block w-4 h-4 rounded-full text-[9px] text-white font-bold text-center leading-4 ${r.is_abnormal ? "bg-jade" : "bg-coral"}`}>{r.id}</span>
                    <span className="text-ink"><span className="font-semibold">{r.label || (r.is_abnormal ? "abnormal" : "not abnormal")}</span>{r.note ? <span className="text-ink-soft"> – {r.note}</span> : null}</span>
                  </li>
                ))}
              </ul>
            </div>
          )}
        </div>
        <div className="space-y-3">
          {sr.consistency_rationale && (
            <div><h3 className="font-bold text-ink text-sm mb-1">Cross-check</h3><p className="text-ink-soft">{sr.consistency_rationale}</p></div>
          )}
          {sr.alternative_considerations && sr.alternative_considerations.length > 0 && (
            <div><h3 className="font-bold text-ink text-sm mb-1">A clinician might also consider</h3>
              <ul className="list-disc pl-4 text-ink-soft space-y-0.5">{sr.alternative_considerations.map((x, i) => <li key={i}>{x}</li>)}</ul></div>
          )}
          {sr.red_flags && sr.red_flags.length > 0 && (
            <div className="rounded-xl bg-coral-tint p-3"><h3 className="flex items-center gap-1.5 font-bold text-coral text-sm mb-1"><Flag size={14} /> Visual red flags</h3>
              <ul className="list-disc pl-4 text-ink space-y-0.5 text-xs">{sr.red_flags.map((x, i) => <li key={i}>{x}</li>)}</ul></div>
          )}
          {sr.suggested_questions && sr.suggested_questions.length > 0 && (
            <div><h3 className="flex items-center gap-1.5 font-bold text-ink text-sm mb-1"><HelpCircle size={14} /> Questions a clinician would ask</h3>
              <ul className="list-disc pl-4 text-ink-soft space-y-0.5 text-xs">{sr.suggested_questions.map((x, i) => <li key={i}>{x}</li>)}</ul></div>
          )}
        </div>
      </div>
    </Card>
  );
}
